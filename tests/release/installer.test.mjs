test('manual installer embeds a fail-closed exact identity gate and shared startup lifecycle',()=>{
 const gate=readFileSync('scripts/release/installer.nsh','utf8')
 assert.match(gate,/!macro customCheckAppRunning/)
 assert.match(gate,/BUILD_UNINSTALLER/)
 assert.match(gate,/\$\{Silent\}/)
 assert.match(gate,/\$\{isUpdated\}/)
 assert.match(gate,/PLANRAIL_INSTALL_MANUAL/)
 assert.match(gate,/install-gate\.ps1/)
 assert.match(gate,/SetErrorLevel 2/)
 assert.doesNotMatch(gate,/taskkill|Stop-Process|KILL_PROCESS|nsProcess::Kill/i)
 assert.match(gate,/SetEnvironmentVariableW/)
 assert.match(gate,/Page custom PlanrailStartupPage PlanrailStartupLeave/)
 assert.match(gate,/!macro customInstall/)
 assert.match(gate,/!macro customUnInstall/)
 const helper=readFileSync('resources/windows/install-gate.ps1','utf8')
 for(const token of ['GetProcessTimes','QueryFullProcessImageName','OpenProcessToken','WindowsIdentity','TerminateProcess','WaitForSingleObject','0.8.0','--planrail-install-exit','--planrail-install-target'])assert.ok(helper.includes(token),token)
 assert.doesNotMatch(helper,/taskkill|Stop-Process|ExecutionPolicy|RunAs/i)
 const c=load(readFileSync('electron-builder.yml','utf8'))
 assert.ok(c.extraResources.some(r=>r.from==='resources/windows/login-startup.ps1'))
})
