import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { createRequire } from 'node:module'
const require=createRequire(import.meta.url)
const {load}=require('js-yaml')
test('per-user assisted installer exposes checked launch without deleting data',()=>{
  const c=load(readFileSync('electron-builder.yml','utf8'))
  assert.equal(c.nsis.oneClick,false)
  assert.equal(c.nsis.runAfterFinish,true)
  assert.equal(c.nsis.perMachine,false)
  assert.equal(c.nsis.allowElevation,false)
  assert.equal(c.nsis.deleteAppDataOnUninstall,false)
  assert.equal(c.win.requestedExecutionLevel,'asInvoker')
})
test('installer configuration conforms to the installed builder schema',async()=>{
  const {validateConfiguration}=require('app-builder-lib/out/util/config/config.js')
  await validateConfiguration(load(readFileSync('electron-builder.yml','utf8')),{add(){}})
})
test('the P icon provides native Windows sizes for window, tray and installer',()=>{
  const c=load(readFileSync('electron-builder.yml','utf8'))
  assert.equal(c.win.icon,'resources/icon.ico')
  assert.ok(c.files.includes('resources/icon.png'), 'package the window icon referenced by main')
  assert.ok(c.files.includes('resources/icon.ico'), 'package the native Windows icon referenced by main')
  assert.equal(c.nsis.installerIcon,c.win.icon)
  assert.equal(c.nsis.uninstallerIcon,c.win.icon)
  const ico=readFileSync(c.win.icon)
  assert.equal(ico.readUInt16LE(2),1)
  assert.equal(ico.readUInt16LE(4),6)
  const sizes=Array.from({length:6},(_,i)=>ico[6+i*16]||256)
  assert.deepEqual(sizes.sort((a,b)=>a-b),[16,24,32,48,64,256])
  const bootstrap=readFileSync('src/main/bootstrap.ts','utf8')
  assert.match(bootstrap,/import windowsIcon from '..\/..\/resources\/icon.ico\?asset'/)
  assert.match(bootstrap,/const desktopIcon = process.platform === 'win32' \? windowsIcon : icon/)
  assert.match(bootstrap,/createTray\)\(desktopIcon,/)
  const png=readFileSync('resources/icon.png')
  assert.equal(png.subarray(1,4).toString(),'PNG')
})

test('Planrail rename preserves installer identity and offers directory selection without elevation',()=>{
 const c=load(readFileSync('electron-builder.yml','utf8'))
 const pkg=JSON.parse(readFileSync('package.json','utf8'))
 assert.equal(c.productName,'Planrail')
 assert.equal(c.win.executableName,'Planrail')
 assert.match(c.artifactName,/^Planrail-/)
 assert.equal(c.appId,'com.kdydesign.simpletimeline')
 assert.equal(pkg.name,'simple-timeline')
 assert.equal(pkg.version,'0.6.9')
 const lock=JSON.parse(readFileSync('package-lock.json','utf8'))
 assert.equal(lock.version,pkg.version)
 assert.equal(lock.packages[''].version,pkg.version)
 assert.equal(c.nsis.include,'scripts/release/installer.nsh')
 assert.notEqual(c.nsis.allowToChangeInstallationDirectory,true)
 assert.equal(c.nsis.packElevateHelper,false)
})
